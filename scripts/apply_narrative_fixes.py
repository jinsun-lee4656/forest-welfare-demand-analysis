def to_source(text: str):
    lines = text.split("\n")
    while lines and lines[0] == "":
        lines.pop(0)
    while lines and lines[-1] == "":
        lines.pop()
    return [l + "\n" for l in lines[:-1]] + [lines[-1]] if lines else []


def find_index(cells, marker):
    """하드코딩된 인덱스는 이후 세션에서 다른 셀들이 여럿 추가/삽입되며 더 이상 유효하지
    않으므로(2026-08-30 재실행 시 발견), expect_substr을 anchor로 써서 동적으로 찾는다."""
    hits = [i for i, c in enumerate(cells) if marker in "".join(c["source"])]
    if len(hits) != 1:
        raise AssertionError(f"anchor {marker!r} 매칭 {len(hits)}건 (1건이어야 함): hits={hits}")
    return hits[0]


def replace_cell(cells, idx, text, expect_substr=None):
    if expect_substr is not None:
        idx = find_index(cells, expect_substr)
    c = cells[idx]
    src = "".join(c["source"])
    if expect_substr and expect_substr not in src:
        raise AssertionError(f"cells[{idx}]에 예상 문자열이 없습니다: {expect_substr!r}\n실제 내용: {src[:200]}")
    c["source"] = to_source(text)


